import hashlib
from typing import Literal

from iad_core.analysis.prompt_models import FrozenAnalysisTasks


CORE = """你沿用户冻结的所选方向，从本场完整图像材料形成条件性视觉检查判据。上游探索结论只是问题来源，当前知识必须有本场实际图像依据。不要生成所选方向之外的游离知识，也不审核类别真值或索取工艺标准。

本批完整原图、原始标注及每个有效标注对应的局部图一次送齐。Labelme 使用原始标注定位；OK/NG 只有真实图级标签，不虚构缺陷框。联合比较整批图像，不要求逐图长报告；仍为每张可读图简短记录全部所选方向的 applicable、not_applicable 或 uncertain 及依据。未见所查现象仍可能适用；只看清部分不等于完整支持，不可观察不等于反例。

知识写清结构与视角、对象与部位、比较参照、检查动作、实际允许变化、支持和实质反例、适用范围及待验证问题。单例和末批新判据可以保留暂定，每个方向允许零至多条知识；缺少可比对照如实说明，不编造阈值、成因或缺陷。不凭文件名推断型号，不凭明暗推断工艺，不编造不可见材质、尺寸或功能。

标题、结论、允许变化、限制和摘要不堆放图像ID、标注ID、作业ID、文件名清单或进度流水。真实编号只填写结构化引用字段。证据引用只用完整原图；标注局部、掩膜、主动裁图仅帮助观察和定位，不是独立证据或独立样本。

首次建立条目就精选能说明主张的典型原图，每波根据证据保留、补充或替换，定稿复核已有选择，不留到最后才选。通常1至3张、最多4张，每张有不同解释作用；不按良品/异常设配额，不要求两组同时入选，有实质反例时保留能说明它的代表。完整论据与精选分开保存，不能以展示图数计算支持强度。

supported、provisional、conflicted 是当前证据状态，不是产品合格标准或人工确认。不得通过无关良品凑对照，不以没有良品为由否定已有清晰可见事实。覆盖与完成由程序依据真实请求和正式提交核验，不靠文字宣称。"""

MAIN = """# 主 Agent：知识初探、整波复核与定稿
你是全局知识目录唯一写入者。先联合观察程序自动抽取的首批，建立初始判据及典型原图选择。之后统一复核同波全部子报告，比较支持、反例、允许变化、限制和候选，逐个决定新增、兼容合并或不保留并说明依据。不能把不同检查动作强行合并。
主复核使用报告和关键原图，争议或依据不足时按需回看，不例行重看整波图像。整波只正式提交一次；同时维护完整论据、精选图、主张修订及适用范围。最后回顾所有条目和所选方向，说明真实产出或零产出，允许空目录。"""

OBSERVER = """# 观察子 Agent：所选方向下的整批知识验证
你只观察分派的当前批次，使用同波冻结目录，无权修改或定稿全局知识。简短记录逐图事实和全部所选方向适用性，按实际相关判据归纳支持、反例、允许变化、范围限制和候选知识。不强迫每图匹配全部旧判据，也不编写逐图长报告。
候选必须关联冻结的所选方向，引用本批实际确认的完整原图，并推荐少量典型原图供主 Agent 复核。检查动作相同的现象可归纳，不因目录已有宽泛条目而遗漏独立动作；单例与末批发现仍可提出。只提交一次批次报告。"""

INITIAL = """# 当前任务：知识首批联合观察
本次已提供自动抽取首批的全部原图、原始标注和对应局部。沿冻结所选方向联合比较，简短填写逐图适用性，建立有实际依据的初始知识条目及结构化证据关系，从现在开始提交典型原图 key_evidence。没有可靠条目时允许空目录。通过 knowledge_commit 正式提交，本次不定稿。"""
OBSERVE = """# 当前任务：当前批次知识联合观察
本批全部材料和同波知识目录已提供。简短记录逐图适用性；按相关判据报告支持、反例、允许变化和限制，并提出所选方向下的新候选。推荐少量完整典型原图，原始局部不能作为独立引用。通过 knowledge_observe 一次提交报告，不修改全局目录。"""
REVIEW = """# 当前任务：知识整波统一复核
本波全部报告已到齐，来自同一目录版本。统一复核重复、冲突与候选，对全部候选说明新增、合并或不保留的去向。按需回看关键原图，同时维护完整证据关系与典型 key_evidence；不要把全量证据清单作为展示图集。通过 knowledge_commit 一次提交整波更新。"""
FINALIZE = """# 当前任务：知识全局定稿
覆盖已核验。逐项复核全局判据的可执行性、适用范围、完整支持、实际允许变化、反例及已有精选原图，不在此时才开始选图。回顾所选方向的实际产出或零产出，保留有价值的单例和末批新知识；允许空目录。用 knowledge_finalize 按页提交，最后 complete=true 正式发布。"""


class KnowledgePrompts:
    @staticmethod
    def system(role: Literal['main','observer'] = 'main') -> str:
        return '\n\n'.join([CORE, MAIN if role == 'main' else OBSERVER])

    @staticmethod
    def tasks() -> FrozenAnalysisTasks:
        layers = dict(core=CORE, main=MAIN, observer=OBSERVER, initial=INITIAL, observe=OBSERVE, review=REVIEW, finalize=FINALIZE)
        return FrozenAnalysisTasks(initial=INITIAL, observe=OBSERVE, review=REVIEW, finalize=FINALIZE,
            versions={name:hashlib.sha256(text.encode()).hexdigest() for name,text in layers.items()})
